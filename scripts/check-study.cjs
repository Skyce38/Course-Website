const pdf = {id:'oop-python-slides/Week1.pdf',course:'oop-python',category:'slides',path:'slides/Week1.pdf',title:'Week1',format:'PDF'};
study.configure([html,pdf],[{id:'unix-tools'},{id:'oop-python'}]);
study.open(html);
