assert.equal(study.position(html.id).sectionOffset,-50,'Sections below the viewport top need signed offsets');
study.open(html);
assert.equal(study.position(html.id).scroll,1234,'Opening must preserve positions');
study.toggleCompleted(pdf.id);
assert.equal(study.progress([pdf,pdf]).total,1);
assert.equal(study.progress([pdf,pdf]).completed,1);
assert.equal(study.progress([html]).completed,0);
assert.equal(study.progress([]).total,0);
study.toggleCompleted(pdf.id);
assert.equal(study.isCompleted(pdf.id),false);
