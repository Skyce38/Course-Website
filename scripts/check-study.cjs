const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const storage = new Map([['skyce-learning-preferences','{"theme":"dark"}'],['skyce-learning-bookmarks','["saved"]']]);
const events = {};
