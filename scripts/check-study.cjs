for(let i=0;i<25;i++)study.open({...html,id:'document-'+i});
assert.equal(study.recent.length,20);
assert.equal(study.recent[0].id,'document-24');
assert.equal(study.position(pdf.id).page,7,'Positions must survive the recent-list limit');
study.resetPosition(pdf.id);
assert.equal(Object.keys(study.position(pdf.id)).length,0);
study.flush(); events.storage({key:'skyce-learning-study'});
assert.equal(study.position(html.id).scroll,1234,'Positions must survive storage reloads');
assert.equal(storage.get('skyce-learning-preferences'),'{"theme":"dark"}');
assert.equal(storage.get('skyce-learning-bookmarks'),'["saved"]');
storage.set('skyce-learning-study',JSON.stringify({recent:[html,html],completed:[html.id,html.id]}));
events.storage({key:'skyce-learning-study'});
assert.equal(study.recent.length,1);
assert.equal(study.progress([html]).completed,1);
storage.set('skyce-learning-study','{broken');
events.storage({key:'skyce-learning-study'});
